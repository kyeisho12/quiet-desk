-- Quiet Desk shared conference chat
-- Run after supabase_account_migration.sql and before supabase_chat_access.sql.

begin;

create table if not exists public.chat_messages (
  id bigint generated by default as identity primary key,
  room_key text not null default 'general',
  account_id uuid not null references public.accounts(id) on delete cascade,
  recipient_account_id uuid references public.accounts(id) on delete cascade,
  author_username text not null,
  body text not null check (length(trim(body)) > 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.chat_messages
  add column if not exists recipient_account_id uuid references public.accounts(id) on delete cascade;

create index if not exists chat_messages_room_created_idx
  on public.chat_messages (room_key, created_at desc);

create index if not exists chat_messages_private_pair_idx
  on public.chat_messages (account_id, recipient_account_id, created_at desc);

alter table public.chat_messages enable row level security;

do $$
begin
  if exists (select 1 from pg_publication where pubname = 'supabase_realtime')
    and not exists (
      select 1
      from pg_publication_tables
      where pubname = 'supabase_realtime'
        and schemaname = 'public'
        and tablename = 'chat_messages'
    ) then
    execute 'alter publication supabase_realtime add table public.chat_messages';
  end if;
end;
$$;

commit;
