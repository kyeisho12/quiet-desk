-- Quiet Desk shared conference chat
-- Run after supabase_account_migration.sql and before supabase_chat_access.sql.

begin;

create table if not exists public.chat_messages (
  id bigint generated by default as identity primary key,
  room_key text not null default 'general',
  account_id uuid not null references public.accounts(id) on delete cascade,
  recipient_account_id uuid references public.accounts(id) on delete cascade,
  author_username text not null,
  body text not null default '',
  image_url text,
  image_path text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.chat_messages
  add column if not exists recipient_account_id uuid references public.accounts(id) on delete cascade;
alter table public.chat_messages
  add column if not exists image_url text;
alter table public.chat_messages
  add column if not exists image_path text;
alter table public.chat_messages
  alter column body set default '';
alter table public.chat_messages
  drop constraint if exists chat_messages_body_check;
alter table public.chat_messages
  add constraint chat_messages_body_or_image_check
  check (length(trim(body)) > 0 or image_url is not null);

insert into storage.buckets (id, name, public)
values ('chat-images', 'chat-images', true)
on conflict (id) do update set public = true;

create index if not exists chat_messages_room_created_idx
  on public.chat_messages (room_key, created_at desc);

create index if not exists chat_messages_private_pair_idx
  on public.chat_messages (account_id, recipient_account_id, created_at desc);

create table if not exists public.chat_reads (
  account_id uuid not null references public.accounts(id) on delete cascade,
  peer_account_id uuid not null references public.accounts(id) on delete cascade,
  last_read_at timestamptz not null default now(),
  primary key (account_id, peer_account_id),
  check (account_id <> peer_account_id)
);

create or replace function public.delete_expired_chat_messages()
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  deleted_count integer;
begin
  delete from public.chat_messages
  where created_at < now() - interval '30 days';

  get diagnostics deleted_count = row_count;
  return deleted_count;
end;
$$;

alter table public.chat_messages enable row level security;

do $$
begin
  if exists (select 1 from pg_publication where pubname = 'supabase_realtime')
    and not exists (
      select 1
      from pg_publication_tables
      where pubname = 'supabase_realtime'
        and schemaname = 'public'
        and tablename = 'chat_messages'
    ) then
    execute 'alter publication supabase_realtime add table public.chat_messages';
  end if;
end;
$$;

commit;

